    def optimize_recalibration_ratio(self, mu, target, logvar, criterion = "NLL", optimizer_bounds = (1e-2, 1e2)):
        """Scale factor which uniformly recalibrates predicted variance.
        Searches via black-box optimization the variance scale factor (opt_ratio)
        which produces the best recalibration, i.e. updated variance
        can be written as opt_ratio * logvar.
        """
        print('Performing black-box optimization of the variance scale factor for the {} model'.format(type(self).__name__))

        if criterion == "NLL":
            cal_fn = self.get_loss_recal
        else:
            raise RuntimeError("Wrong criterion option")
        def obj(ratio):
            # If ratio is 0, return worst-possible calibration metric
            if ratio == 0:
                raise Warning("Ratio is equals to zero")
            curr_cal = cal_fn(mu, target, ratio * logvar)
            return curr_cal
        result = minimize_scalar(fun=obj, bounds=optimizer_bounds)
        opt_ratio = result.x
        if not result.success:
            raise Warning("Optimization did not succeed")
            original_cal = cal_fn(mu, target, logvar)
            ratio_cal = cal_fn(mu, target, opt_ratio * logvar)
            if ratio_cal > original_cal:
                raise Warning(
                    "No better calibration found, no recalibration performed and returning original uncertainties"
                )
                opt_ratio = 1.0
        return opt_ratio

