    def intersection(self, p1, p2, p3, p4):
        """Calculate the intersection of two lines between four points"""
        x1, y1 = p1
        x2, y2 = p2
        x3, y3 = p3
        x4, y4 = p4
        D = (x1 - x2) * (y3 - y4) - (y1 - y2) * (x3 - x4)
        x = ((x1 * y2 - y1 * x2) * (x3 - x4) - (x1 - x2) * (x3 * y4 - y3 * x4)) / D
        y = ((x1 * y2 - y1 * x2) * (y3 - y4) - (y1 - y2) * (x3 * y4 - y3 * x4)) / D
        return x, y

    def trapezoid_area(self, xl, al, bl, xr, ar, br, absolute = True):
        """Calculate the area of a vertical-sided trapezoid"""
        # Differences
        dl = bl - al
        dr = br - ar
        # The ordering is the same for both iff they do not cross.
        cross = dl * dr < 0
        # Treat the degenerate case as a trapezoid
        cross = cross * (1 - ((dl == 0) * (dr == 0)))
        # trapezoid for non-crossing lines
        area_trapezoid = (xr - xl) * 0.5 * ((bl - al) + (br - ar))
        if absolute:
            area_trapezoid = np.abs(area_trapezoid)
        with np.errstate(divide="ignore", invalid="ignore"):
            x_intersect = self.intersection((xl, bl), (xr, br), (xl, al), (xr, ar))[0]
        tl_area = 0.5 * (bl - al) * (x_intersect - xl)
        tr_area = 0.5 * (br - ar) * (xr - x_intersect)
        if absolute:
            area_hourglass = np.abs(tl_area) + np.abs(tr_area)
        else:
            area_hourglass = tl_area + tr_area
        # The nan_to_num function allows us to do 0 * nan = 0
        return (1 - cross) * area_trapezoid + cross * np.nan_to_num(area_hourglass)

    def miscalibration_area_from_proportions(self, exp_proportions, obs_proportions):
        """Miscalibration area from expected and observed proportions lists..
        """
        areas = self.trapezoid_area(
            exp_proportions[:-1],
            exp_proportions[:-1],
            obs_proportions[:-1],
            exp_proportions[1:],
            exp_proportions[1:],
            obs_proportions[1:],
            absolute=True)
        return areas.sum()

    def miscalibration_area(self, y_pred, y_std, y_true, num_bins = 100, vectorized = False, recal_model = None, prop_type = "interval"):
        """Miscalibration area.
        This is identical to mean absolute calibration error and ECE, however
        the integration here is taken by tracing the area between curves.
        """
        # Compute the expected proportions and the residuals.
        exp_proportions = np.linspace(0, 1, num_bins)
        if recal_model is not None:
            in_exp_proportions = recal_model.predict(exp_proportions)
        else:
            in_exp_proportions = exp_proportions
        residuals = y_pred - y_true
        # Get the inverse of the CDF at each of these depending on the prop_type.
        if prop_type == "interval":
            expected_sd_multiples = norm(0, 1).ppf(0.5 + in_exp_proportions / 2.0)
            sd_multiples = np.abs(residuals) / y_std
        elif prop_type == "quantile":
            expected_sd_multiples = norm(0, 1).ppf(in_exp_proportions)
            sd_multiples = residuals / y_std
        else:
            raise ValueError(f"Unknown prop_type {prop_type}")
        # For each bin edge, see how many of our data points deviate less than the
        # corresponding sd multiple.
        if vectorized:
            obs_proportions = (sd_multiples.reshape(-1, 1) <= expected_sd_multiples).mean(0)
        else:
            obs_proportions = np.array(
                [
                    np.mean(sd_multiples <= expected_sd_multiples[i], dtype=np.float64)
                    for i in range(len(expected_sd_multiples))
                ]
            )
        # Calculate and return the area between these and the line y=x.
        miscal_area = self.miscalibration_area_from_proportions(exp_proportions, obs_proportions)
        return miscal_area

